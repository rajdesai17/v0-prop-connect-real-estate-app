// Helper functions
export function getPropertyById(id: string): Property | undefined {
  return properties.find((p) => p.id === id)
}

export function getPropertiesByAgent(agentId: string): Property[] {
  return properties.filter((p) => p.agent.id === agentId)
}

export function getFeaturedProperties(): Property[] {
  return properties.filter((p) => p.isFeatured)
}

export function getPropertiesByIds(ids: string[]): Property[] {
  return properties.filter((p) => ids.includes(p.id))
}

export function getUserByEmail(email: string): User | undefined {
  return users.find((u) => u.email === email)
}

export function getUserById(id: string): User | undefined {
  return users.find((u) => u.id === id)
}
